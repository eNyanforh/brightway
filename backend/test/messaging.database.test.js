import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createMessagingService } from "../src/modules/messaging/messaging.service.js";
import { createNotificationsService } from "../src/modules/notifications/notifications.service.js";

const skip = !process.env.TEST_DATABASE_URL && "Set TEST_DATABASE_URL to a migrated isolated test database";
test("Sprint 8 messaging enforces connections, blocks, private files, monotonic receipts, presence privacy and audited official authority", { skip }, async () => {
  const { PrismaClient } = await import("@prisma/client"), { PrismaPg } = await import("@prisma/adapter-pg");
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.TEST_DATABASE_URL }), transactionOptions: { timeout: 15000, maxWait: 10000 } });
  let timestamp = new Date("2030-01-15T12:00:00Z"); const now = () => timestamp;
  const objects = new Map(), accounts = [], staffIds = [], orgIds = [], requestIds = [];
  const storage = { check() {}, async put(key, bytes) { objects.set(key, bytes); }, async get(key) { return objects.get(key); }, async delete(key) { objects.delete(key); } };
  const service = createMessagingService({ prisma: db, storage, now, processFile: async bytes => ({ bytes, contentType: "application/pdf" }) });
  const notices = createNotificationsService({ prisma: db, now });
  async function person(label) {
    const marker = randomUUID().slice(0, 8);
    const a = await db.account.create({ data: { username: `msg_${label}_${marker}`, email: `${label}_${marker}@example.invalid`, emailVerifiedAt: now(), passwordHash: "unusable-synthetic", person: { create: { firstName: "Synthetic", lastName: label } } } }); accounts.push(a);
    await db.mfaFactor.create({ data: { accountId: a.id, enabled: true, encryptedSecret: "synthetic", version: 1, windowStart: now() } });
    const s = await db.session.create({ data: { accountId: a.id, tokenHash: randomUUID(), expiresAt: new Date("2031-01-01"), mfaVerifiedAt: now(), mfaVersion: 1 } });
    return { ...a, actor: { accountId: a.id, sessionId: s.id } };
  }
  async function connect(a, b) { const [leftAccountId, rightAccountId] = [a.id, b.id].sort(); return db.networkPair.create({ data: { leftAccountId, rightAccountId, status: "CONNECTED", version: 1 } }); }
  async function staff(capabilities) {
    const id = "mg_" + randomUUID(); staffIds.push(id);
    const a = await db.managementStaff.create({ data: { id, username: "msg_" + randomUUID().slice(0, 8), fullName: "Synthetic staff", email: id + "@example.invalid", passwordHash: "synthetic", status: "ACTIVE", emailVerifiedAt: now(), encryptedSecret: "synthetic", capabilities, recoveryHashes: [] } });
    const s = await db.managementSession.create({ data: { staffId: id, tokenHash: randomUUID(), expiresAt: new Date("2031-01-01"), mfaVerifiedAt: now(), staffVersion: a.version } });
    return { staffId: id, sessionId: s.id };
  }
  try {
    const a = await person("alice"), b = await person("bob"), outsider = await person("stranger"), d = await person("dora");
    await assert.rejects(service.open(a.actor, a.username), { status: 404 });
    await assert.rejects(service.open(a.actor, b.username), { status: 403 });
    await db.networkFollow.create({ data: { followerId: a.id, targetAccountId: b.id, active: true } });
    await assert.rejects(service.open(a.actor, b.username), { status: 403 }, "following is not a connection");
    const pair = await connect(a, b); await connect(a, d);
    const c = await service.open(a.actor, b.username), other = await service.open(a.actor, d.username);
    assert.equal((await service.open(b.actor, a.username)).id, c.id, "both directions share one direct thread");
    const body = { body: "Discuss our education project", requestKey: randomUUID() };
    const first = await service.send(a.actor, c.id, body);
    assert.equal(first.state, "SENT"); assert.equal(first.deliveredAt, null);
    assert.equal((await service.send(a.actor, c.id, body)).id, first.id, "ambiguous retries cannot duplicate sends");
    await assert.rejects(service.send(a.actor, c.id, { ...body, body: "Changed body" }), { status: 409 });
    await assert.rejects(service.send(outsider.actor, c.id, { body: "intrusion", requestKey: randomUUID() }), { status: 404 });
    await assert.rejects(service.detail(outsider.actor, c.id), { status: 404 });
    await assert.rejects(service.receipts(outsider.actor, c.id, { state: "READ", throughId: first.id }), { status: 404 });
    assert.equal((await service.detail(b.actor, c.id)).conversation.unread, 1);
    await service.receipts(a.actor, c.id, { state: "READ", throughId: first.id });
    assert.equal((await service.detail(a.actor, c.id)).items[0].state, "SENT", "sender cannot mark their own message read");
    timestamp = new Date(+timestamp + 1000);
    await service.receipts(b.actor, c.id, { state: "DELIVERED", throughId: first.id });
    assert.equal((await service.detail(a.actor, c.id)).items[0].state, "DELIVERED");
    timestamp = new Date(+timestamp + 1000);
    await service.receipts(b.actor, c.id, { state: "READ", throughId: first.id });
    const read = (await service.detail(a.actor, c.id)).items[0]; assert.equal(read.state, "READ"); assert(read.readAt >= read.deliveredAt);
    const deliveredAt = read.deliveredAt;
    await service.receipts(b.actor, c.id, { state: "DELIVERED", throughId: first.id });
    assert.equal(+(await service.detail(a.actor, c.id)).items[0].deliveredAt, +deliveredAt);
    await assert.rejects(db.directMessage.update({ where: { id: first.id }, data: { body: "rewrite audit" } }), /immutable/);
    const second = await service.send(a.actor, c.id, { body: "A new unseen message", requestKey: randomUUID() });
    await service.receipts(b.actor, c.id, { state: "READ", throughId: first.id });
    assert.equal((await db.directMessage.findUnique({ where: { id: second.id } })).readAt, null, "read boundary excludes a racing unseen message");
    await service.heartbeat(a.actor);
    assert.equal((await service.detail(b.actor, c.id)).presence.lastActiveAt, null, "active status defaults to private");
    await service.preferences(a.actor, { showActive: true, showTyping: true });
    assert.equal((await service.detail(b.actor, c.id)).presence.active, true);
    await service.typing(a.actor, c.id, { active: true });
    assert.equal((await service.detail(b.actor, c.id)).presence.typing, true);
    timestamp = new Date(+timestamp + 7000);
    assert.equal((await service.detail(b.actor, c.id)).presence.typing, false, "typing expires without a stop event");
    await service.preferences(a.actor, { showActive: false, showTyping: false });
    await service.typing(a.actor, c.id, { active: true });
    assert.deepEqual((await service.detail(b.actor, c.id)).presence, { active: false, lastActiveAt: null, typing: false });
    const f = await service.upload(a.actor, c.id, { name: "research.pdf" }, Buffer.from("synthetic PDF"), "application/pdf");
    await assert.rejects(service.file(b.actor, c.id, f.id), { status: 404 }, "unattached files are owner-only");
    await assert.rejects(service.send(a.actor, other.id, { attachmentIds: [f.id], requestKey: randomUUID() }), { status: 400 });
    await assert.rejects(service.send(b.actor, c.id, { attachmentIds: [f.id], requestKey: randomUUID() }), { status: 400 });
    const withFile = await service.send(a.actor, c.id, { attachmentIds: [f.id], requestKey: randomUUID() });
    assert.equal(withFile.attachments.length, 1);
    assert.equal((await service.file(b.actor, c.id, f.id)).bytes.toString(), "synthetic PDF");
    await assert.rejects(service.file(outsider.actor, c.id, f.id), { status: 404 });
    const discarded = await service.upload(a.actor, c.id, { name: "draft.pdf" }, Buffer.from("discard me"), "application/pdf");
    await service.discardFile(a.actor, c.id, discarded.id);
    assert.equal(await db.messageAttachment.count({ where: { id: discarded.id } }), 0);
    assert.equal(await db.messagingUploadAttempt.count({ where: { accountId: a.id } }), 2, "discarding cannot reset processing budget");
    await assert.rejects(service.discardFile(a.actor, c.id, f.id), { status: 404 }, "sent attachments cannot be discarded");
    const attempts = Array.from({ length: 49 }, () => ({ id: randomUUID(), accountId: a.id, inputSize: 1, createdAt: now() }));
    await db.messagingUploadAttempt.createMany({ data: attempts });
    await assert.rejects(service.upload(a.actor, c.id, { name: "over-budget.pdf" }, Buffer.from("too many"), "application/pdf"), { status: 429 });
    await db.messagingUploadAttempt.deleteMany({ where: { id: { in: attempts.map(a => a.id) } } });
    const draft = await service.upload(a.actor, c.id, { name: "abandoned.pdf" }, Buffer.from("unbound"), "application/pdf");
    timestamp = new Date(+timestamp + 86400001);
    assert.equal((await service.cleanupDraftFiles()).deleted, 1);
    assert.equal(await db.messageAttachment.count({ where: { id: draft.id } }), 0);
    assert.equal((await service.file(b.actor, c.id, f.id)).bytes.toString(), "synthetic PDF", "maintenance never removes bound files");
    await db.directMessage.createMany({ data: Array.from({ length: 45 }, (_, i) => ({ conversationId: c.id, senderAccountId: a.id, requestKey: randomUUID(), requestHash: "a".repeat(64), body: "Ordered message " + i, createdAt: now() })) });
    const page1 = await service.detail(a.actor, c.id);
    assert.equal(page1.items.length, 40); assert(page1.nextCursor);
    const page2 = await service.detail(a.actor, c.id, { cursor: page1.nextCursor });
    assert.equal(new Set([...page1.items, ...page2.items].map(m => m.id)).size, page1.items.length + page2.items.length);
    assert(page1.items.every((m, i) => i === 0 || BigInt(m.sequence) > BigInt(page1.items[i - 1].sequence)), "same-time messages keep database sequence order");
    await assert.rejects(service.detail(a.actor, other.id, { cursor: page1.nextCursor }), { status: 400 });

    timestamp = new Date(+timestamp + 61000);
    const shared = await service.resolveShare(a.actor, { path: `/${d.username}` });
    assert.equal(shared.kind, "PROFILE");
    assert.equal((await service.send(a.actor, c.id, { share: { kind: shared.kind, id: shared.id }, requestKey: randomUUID() })).share.href, `/${d.username}`);
    await assert.rejects(service.resolveShare(a.actor, { path: "//evil.invalid/profile" }), { status: 400 });
    await assert.rejects(service.send(a.actor, c.id, { share: { kind: "PROGRAM", id: randomUUID() }, requestKey: randomUUID() }), { status: 404 });
    await db.networkPair.update({ where: { id: pair.id }, data: { status: "NONE" } });
    assert.equal((await service.detail(a.actor, c.id)).conversation.canSend, false);
    await assert.rejects(service.send(a.actor, c.id, { body: "removed", requestKey: randomUUID() }), { status: 403 });
    await assert.rejects(service.typing(a.actor, c.id, { active: true }), { status: 403 });
    await db.networkPair.update({ where: { id: pair.id }, data: { leftBlocked: true } });
    await assert.rejects(service.detail(a.actor, c.id), { status: 404 });
    await assert.rejects(service.file(b.actor, c.id, f.id), { status: 404 });
    assert.equal((await service.list(a.actor)).items.some(i => i.id === c.id), false);
    assert.equal((await notices.list(b.actor)).items.length, 0, "blocked-actor notifications are hidden");
    const admin = await staff(["support-agent"]), denied = await staff(["audit-reader"]);
    const official = { recipientKind: "USER", recipientId: b.id, body: "Welcome to BrightWay", reason: "Welcome and onboarding assistance", requestKey: randomUUID() };
    await assert.rejects(service.official(a.actor, official), { status: 403 });
    await assert.rejects(service.official(denied, official), { status: 403 });
    const saved = await service.official(admin, official);
    assert.deepEqual(await service.official(admin, official), saved);
    const detail = await service.detail(b.actor, saved.conversationId);
    assert.equal(detail.items[0].sender.fullName, "BrightWay");
    assert.equal(JSON.stringify(detail).includes(admin.staffId), false, "staff actor stays out of recipient API");
    const audit = await db.managementAction.findUnique({ where: { actorId_requestKey: { actorId: admin.staffId, requestKey: official.requestKey } } });
    assert.equal(audit.result.messageId, saved.messageId); assert.equal(audit.actorId, admin.staffId);
    await service.send(b.actor, saved.conversationId, { body: "Thank you", requestKey: randomUUID() });
    assert.equal((await service.detail(admin, saved.conversationId)).items.at(-1).body, "Thank you");
    await assert.rejects(service.detail(admin, other.id), { status: 404 }, "management cannot inspect personal DMs");
    const failureDb = { $transaction: (work, options) => db.$transaction(tx => work(new Proxy(tx, { get(target, key) { if (key === "managementAction") return { ...target.managementAction, create: async () => { throw Error("Synthetic audit failure"); } }; const value = target[key]; return typeof value === "function" ? value.bind(target) : value; } })), options) };
    const failureService = createMessagingService({ prisma: failureDb, storage, now }); const failedKey = randomUUID();
    await assert.rejects(failureService.official(admin, { ...official, requestKey: failedKey }), /Synthetic audit failure/);
    assert.equal(await db.directMessage.count({ where: { requestKey: failedKey } }), 0, "official sends and staff audit commit atomically");
    const request = await db.organizationRequest.create({ data: { applicantId: a.id, assignedAgentId: b.id, decidedById: d.id, decidedAt: now(), version: 4, status: "APPROVED", idempotencyKey: randomUUID(), inputHash: "a".repeat(64), fingerprint: randomUUID(), name: "Synthetic messaging org", type: "COMPANY", representativeRole: "Director", countryCode: "LR", region: "Montserrado", city: "Monrovia", address: "Synthetic address", offersTraining: false, targetAt: now() } }); requestIds.push(request.id);
    const org = await db.organization.create({ data: { requestId: request.id, name: request.name, type: "COMPANY", offersTraining: false, verifiedAt: now(), memberships: { create: { accountId: a.id, role: "PRIMARY_ADMIN" } } } }); orgIds.push(org.id);
    const orgMessage = await service.official(admin, { ...official, recipientKind: "ORGANIZATION", recipientId: org.id, requestKey: randomUUID() });
    assert.equal((await service.list(a.actor, { organizationId: org.id })).items.length, 1);
    await assert.rejects(service.detail(b.actor, orgMessage.conversationId), { status: 403 });
    await service.send(a.actor, orgMessage.conversationId, { body: "Organization acknowledges", requestKey: randomUUID() });
    await db.organizationMembership.update({ where: { organizationId_accountId: { organizationId: org.id, accountId: a.id } }, data: { enabled: false } });
    await assert.rejects(service.detail(a.actor, orgMessage.conversationId), { status: 403 }, "revoked organization membership takes effect immediately");
    const inbox = await notices.list(b.actor, undefined, "unread"); assert(inbox.items.some(n => n.kind === "PLATFORM"));
    const n = inbox.items[0]; assert.equal((await notices.markRead(outsider.actor, n.id)).updated, false);
    assert.equal((await notices.markRead(b.actor, n.id)).updated, true);
    await db.managementStaff.update({ where: { id: admin.staffId }, data: { status: "DISABLED" } });
    await assert.rejects(service.detail(admin, saved.conversationId), { status: 403 });
    await db.session.update({ where: { id: d.actor.sessionId }, data: { expiresAt: new Date(+now() - 1000) } });
    await assert.rejects(service.list(d.actor), { status: 401 });
  } finally {
    const ids = accounts.map(a => a.id);
    const convos = await db.messagingConversation.findMany({ where: { OR: [{ leftAccountId: { in: ids } }, { recipientAccountId: { in: ids } }, { organizationId: { in: orgIds } }] }, select: { id: true } });
    const convoIds = convos.map(c => c.id);
    await db.messagingTyping.deleteMany({ where: { conversationId: { in: convoIds } } });
    await db.messageAttachment.deleteMany({ where: { conversationId: { in: convoIds } } });
    await db.directMessage.deleteMany({ where: { conversationId: { in: convoIds } } });
    await db.messagingConversation.deleteMany({ where: { id: { in: convoIds } } });
    await db.platformNotification.deleteMany({ where: { recipientId: { in: ids } } });
    await db.managementAction.deleteMany({ where: { actorId: { in: staffIds } } });
    await db.managementSession.deleteMany({ where: { staffId: { in: staffIds } } });
    await db.reviewPrincipal.deleteMany({ where: { staffId: { in: staffIds } } });
    await db.managementStaff.deleteMany({ where: { id: { in: staffIds } } });
    await db.organizationMembership.deleteMany({ where: { organizationId: { in: orgIds } } });
    await db.organization.deleteMany({ where: { id: { in: orgIds } } });
    await db.organizationRequest.deleteMany({ where: { id: { in: requestIds } } });
    await db.networkFollow.deleteMany({ where: { followerId: { in: ids } } });
    await db.networkPair.deleteMany({ where: { OR: [{ leftAccountId: { in: ids } }, { rightAccountId: { in: ids } }] } });
    await db.session.deleteMany({ where: { accountId: { in: ids } } });
    await db.mfaFactor.deleteMany({ where: { accountId: { in: ids } } });
    await db.reviewPrincipal.deleteMany({ where: { accountId: { in: ids } } });
    await db.account.deleteMany({ where: { id: { in: ids } } });
    await db.person.deleteMany({ where: { id: { in: accounts.map(a => a.personId) } } });
    await db.$disconnect();
  }
});
